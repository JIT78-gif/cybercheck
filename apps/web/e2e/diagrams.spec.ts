import { expect, test } from "@playwright/test";
import { buildAiDiagrams } from "../../api/src/understanding/ai/diagrams";
import { buildDiagrams } from "../../api/src/understanding/diagrams";
import { trickyAi, trickyFacts } from "../../api/test/tricky-facts";

// Projects name things anything: keywords like "end", brackets, quotes, pipes, unicode.
// Every generated diagram must still parse and draw with the real Mermaid library.
test("every generated diagram draws, whatever the project names things", async ({ page }) => {
  const diagrams = buildDiagrams(trickyFacts as unknown as Parameters<typeof buildDiagrams>[0]);
  expect(Object.keys(diagrams).sort()).toEqual(["api_map", "auth_map", "data_model", "dependencies", "deployment", "domain_types", "integrations", "test_map"]);
  // The AI section's diagrams (context, data flow, state machines, sequences) are generated by code too.
  Object.assign(diagrams, buildAiDiagrams(trickyAi as unknown as Parameters<typeof buildAiDiagrams>[0], trickyFacts as unknown as Parameters<typeof buildAiDiagrams>[1]));
  expect(Object.keys(diagrams)).toEqual(expect.arrayContaining(["context", "data_flow", "state:state-1", "sequence:sequence-1"]));

  // Every node is declared once: same-named types, tables and services in different files stay separate.
  for (const [key, code] of Object.entries(diagrams)) {
    const declared = [...code!.matchAll(/^\s*(?:class\s+|subgraph\s+)?([A-Za-z_]\w*)\s*(?:\[|\(\[|\[\()/gm)].map((m) => m[1]!);
    expect(declared.filter((x, i) => declared.indexOf(x) !== i), `${key} duplicate ids`).toEqual([]);
  }

  await page.setContent("<html><body></body></html>");
  await page.addScriptTag({ path: require.resolve("mermaid/dist/mermaid.min.js") });
  for (const [key, code] of Object.entries(diagrams)) {
    const error = await page.evaluate(async ([k, c]) => {
      const m = (window as unknown as { mermaid: { initialize: (o: object) => void; render: (id: string, t: string) => Promise<{ svg: string }> } }).mermaid;
      m.initialize({ startOnLoad: false, securityLevel: "strict" });
      try {
        const { svg } = await m.render(`check-${k.replace(/[^\w-]/g, "_")}`, c);
        return svg.includes("Syntax error") ? "rendered an error image" : null;
      } catch (e) {
        return String((e as Error).message ?? e);
      }
    }, [key, code!] as const);
    expect(error, `${key}\n${code}`).toBeNull();
  }
});
