import { CI_ENV, POLICY, TSX, addFinding, execute, setOb, sha, shq, tail, toProjectPaths, type Ctx } from "./runtime.ts";

// Unit tests written by cybercheck: run as an overlay next to the project, never inside its code.

export type Generated = { workspace: string; files: Array<GeneratedFile & { obligationIds: string[]; overlayPath: string }> };

async function runGeneratedOnce(ctx: Ctx, image: string, g: Generated, label: string, retryOf: string | null, extra: Record<string, string> = {}) {
  const uploads = await Promise.all(g.files.map(async (f) => ({ path: f.overlayPath, fileId: await ctx.provider.upload(Buffer.from(f.code)) })));
  const report = `${OUT}/generated.junit.xml`;
  const r = await execute(ctx, { kind: "generated_tests", label, workspace: g.workspace, retryOf, fetch: [report] }, {
    image,
    command: `mkdir -p ${OUT} && cd ${shq(wsPath(g.workspace))} && node --import ${TSX} --test --test-reporter=spec --test-reporter-destination=stdout --test-reporter=junit --test-reporter-destination=${report} ${g.files.map((f) => shq(f.overlayPath)).join(" ")}`,
    network: false,
    keep: true,
    timeoutSec: 300,
    // Same synthetic settings the app gets: modules that read required settings on import must still load.
    env: { ...CI_ENV, ...appEnv(ctx, { port: 3000, config: [], identities: [] }, extra), NO_COLOR: "1" },
    files: uploads,
  });
  const xml = r.files.get(report);
  return { exec: r.exec, parsed: xml ? parseJunit(xml.toString("utf8")) : null, output: `${r.result.stdout}\n${r.result.stderr}` };
}

/** The test() block of one case in generated code, for triage context. */
function caseCode(code: string, name: string) {
  const i = code.indexOf(name);
  if (i < 0) return code.slice(0, 1500);
  const start = code.lastIndexOf("test(", i);
  return code.slice(Math.max(0, start), Math.min(code.length, start + 1500));
}

export async function judgeGenerated(ctx: Ctx, image: string, g: Generated, candidates: Candidate[]) {
  let extra: Record<string, string> = {};
  let first = await runGeneratedOnce(ctx, image, g, `Generated unit tests (${g.workspace})`, null);
  // Tests that stop on a missing setting are repaired once, like the app's start-up.
  const missing = missingVars(ctx, first.output, {});
  if (missing.length && (!first.parsed || first.parsed.cases.every((c) => c.status !== "passed"))) {
    extra = Object.fromEntries(missing.map((n) => [n, syntheticValue(n, ctx.runId)]));
    first = await runGeneratedOnce(ctx, image, g, `Generated unit tests (${g.workspace}) with ${missing.join(", ")} set`, first.exec.id, extra);
  }
  const statusOf = (p: ParsedSuite | null, name: string) => p?.cases.find((c) => c.name === name || c.name.endsWith(`> ${name}`))?.status ?? null;
  const failedNames = g.files.flatMap((f) => f.cases.filter((c) => ["failed", "error"].includes(statusOf(first.parsed, c.name) ?? "")).map((c) => c.name));
  const second = failedNames.length ? await runGeneratedOnce(ctx, image, g, `Repeat generated unit tests (${g.workspace})`, first.exec.id, extra) : null;
  const execIds = [first.exec.id, ...(second ? [second.exec.id] : [])];
  for (const f of g.files) {
    // Discovery: a file none of whose tests appear in the results did not load. That is cybercheck's own
    // test failing, shown as a testing-system problem, never as quiet inconclusive rows.
    if (f.cases.every((c) => statusOf(first.parsed, c.name) === null)) {
      const why = first.output.split("\n").find((l) => /Error|error:|Cannot find|SyntaxError|is not a function|not exported/.test(l))?.trim().slice(0, 300) ?? "no test from this file appeared in the runner's results";
      const finding = await addFinding(ctx, {
        kind: "test_defect",
        status: "confirmed",
        severity: "low",
        confidence: "high",
        title: `A unit test file cybercheck wrote for ${f.target} did not load`,
        expected: `The ${f.cases.length} generated test(s) run`,
        actual: why,
        reproduction: `node --import tsx --test ${f.overlayPath.split("/").pop()} (the file is generated by cybercheck, not part of your project)`,
        rootCause: "The generated test file could not be loaded by the test runner; this is a problem with cybercheck's test, not with your code.",
        location: null,
        obligationIds: f.obligationIds,
        executionIds: execIds,
        validation: "Test discovery: none of the file's test names appeared in the runner's report.",
        limitation: null,
        layer: "unit",
        nextAction: "Rerun: cybercheck rewrites tests that fail to load.",
      });
      for (const id of f.obligationIds) await setOb(ctx, id, { status: "inconclusive", reachedTarget: false, reason: `cybercheck's generated test did not load (${why.slice(0, 160)}); see ${finding.id}.`, executionIds: execIds, findingIds: [finding.id] });
      continue;
    }
    const fileCandidates: Candidate[] = [];
    for (const [i, c] of f.cases.entries()) {
      const id = f.obligationIds[i]!;
      const s1 = statusOf(first.parsed, c.name);
      if (s1 === null) {
        // The file never loaded or the test did not run: a problem with the generated test, not the product.
        await setOb(ctx, id, { status: "inconclusive", reason: "The generated test did not run (it failed to load or was not found in the results).", executionIds: execIds });
        continue;
      }
      if (s1 === "passed") {
        await setOb(ctx, id, { status: "passed", reason: null, executionIds: execIds });
        continue;
      }
      if (s1 === "skipped") {
        await setOb(ctx, id, { status: "skipped", reason: "The generated test skipped itself.", executionIds: execIds });
        continue;
      }
      const s2 = statusOf(second?.parsed ?? null, c.name);
      if (s2 === "passed") {
        await setOb(ctx, id, { status: "flaky", reason: "Failed once and passed when repeated.", executionIds: execIds });
        continue;
      }
      const failure = first.parsed?.failures.find((x) => x.name === c.name || x.name.endsWith(`> ${c.name}`))?.detail ?? "";
      await setOb(ctx, id, { status: "failed", reason: failure.split("\n")[0]?.slice(0, 200) || "The assertion failed.", executionIds: execIds });
      fileCandidates.push({
        source: "suite",
        label: `Generated test: ${c.name}`,
        obligationIds: [id],
        executionIds: execIds,
        reproduced: s2 ? 2 : 1,
        of: s2 ? 2 : 1,
        context: [
          "A unit test written by cybercheck's test author (not by the project) failed in a clean sandbox. The author may have misread the code: judge the expectation against the cited code before blaming the product.",
          `Rule the test checks: ${c.rule}`,
          `Test code:\n${caseCode(f.code, c.name)}`,
          `Failure:\n${tail(redactSecrets(toProjectPaths(failure)).text, 2000)}`,
          `Repeated in a second clean sandbox: ${s2 ? "failed again" : "not repeated"}.`,
          ...c.evidence.map((e) => excerpt(ctx.src, e.path, e.line, 12, 25)).filter(Boolean),
          // The module under test itself, so triage can tell a wrong test from a wrong product.
          ...(() => {
            const target = ctx.src.files.get(f.target);
            return target ? [`Module under test:\n<project_data file="${f.target}">\n${numbered(target.text, 1, Math.min(target.lines, 260))}\n</project_data>`, ...codeUnderTest(ctx.src, f.target, 6_000)] : [];
          })(),
        ].join("\n\n"),
        locations: c.evidence,
        workspace: g.workspace,
        reproduction: `Run this test, written by cybercheck, with node --test (TypeScript via tsx) from ${g.workspace === "." ? "the project root" : g.workspace}:\n${caseCode(f.code, c.name)}`,
        testNames: [c.name],
      });
    }
    // Many failures in one generated file usually mean the file misread the code: one triage for all of them.
    if (fileCandidates.length > 2) {
      const target = ctx.src.files.get(f.target);
      candidates.push({
        source: "suite",
        label: `Generated test: ${fileCandidates.length} generated tests for ${f.target} fail`,
        obligationIds: fileCandidates.flatMap((c) => c.obligationIds),
        executionIds: execIds,
        reproduced: Math.min(...fileCandidates.map((c) => c.reproduced)),
        of: Math.max(...fileCandidates.map((c) => c.of)),
        context: [
          `${fileCandidates.length} unit tests written by cybercheck's test author (not by the project) for ${f.target} failed in a clean sandbox. When most of a generated file fails, the file usually misread the code; judge each expectation against the module before blaming the product. Classify the group as a whole; if only some failures are real product defects, say product_defect and name the real one in the title and location.`,
          ...fileCandidates.slice(0, 8).map((c) => c.context.split("\n\n").slice(1, 4).join("\n").slice(0, 1400)),
          ...(target ? [`Module under test:\n<project_data file="${f.target}">\n${numbered(target.text, 1, Math.min(target.lines, 260))}\n</project_data>`, ...codeUnderTest(ctx.src, f.target, 6_000)] : []),
        ].join("\n\n"),
        locations: fileCandidates[0]!.locations,
        workspace: g.workspace,
        testNames: fileCandidates.flatMap((c) => c.testNames ?? []),
      });
    } else candidates.push(...fileCandidates);
  }
}

